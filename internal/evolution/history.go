package evolution

import (
	"crypto/rand"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"time"
)

// Experiment records a single retrieval comparison and its gate decision.
type Experiment struct {
	ID            string       `json:"id"`
	CreatedAt     time.Time    `json:"created_at"`
	Before        RetrievalRun `json:"before"`
	After         RetrievalRun `json:"after"`
	Failures      []Failure    `json:"failures"`
	Prediction    Prediction   `json:"prediction"`
	ActualDelta   float64      `json:"actual_delta"`
	Decision      Decision     `json:"decision"`
	AnswerQuality string       `json:"answer_quality"`
	Evaluation    Evaluation   `json:"evaluation"`
}

// NewExperiment gives each run a random identity and explicit quality boundary.
func NewExperiment(before, after RetrievalRun, prediction Prediction, decision Decision) (Experiment, error) {
	var random [16]byte
	if _, err := rand.Read(random[:]); err != nil {
		return Experiment{}, err
	}
	ev := DescribeEvaluation(before, after)
	exp := Experiment{ID: hex.EncodeToString(random[:]), CreatedAt: time.Now().UTC(), Before: before, After: after,
		Failures: DiagnoseRetrieval(before, after), Prediction: prediction, ActualDelta: after.HitRate - before.HitRate,
		Decision: decision, AnswerQuality: ev.LexicalProxy, Evaluation: ev}
	return exp, nil
}

// normalizeExperiment rewrites legacy quality tokens when a record is read.
// It does not persist the rewrite; callers keep the file unchanged.
func normalizeExperiment(exp *Experiment) {
	if exp.Evaluation.SourceHit == "" {
		exp.Evaluation = DescribeEvaluation(exp.Before, exp.After)
	}
	switch exp.AnswerQuality {
	case "", "not_evaluated", "deterministic_proxy":
		exp.AnswerQuality = exp.Evaluation.LexicalProxy
	}
}

var ErrExperimentNotFound = errors.New("experiment not found")

// History stores public-dataset experiments as separate JSON files.
type History struct{ Dir string }

// Save persists one experiment atomically; IDs are generated by NewExperiment.
func (h History) Save(exp Experiment) error {
	if len(exp.ID) != 32 {
		return fmt.Errorf("invalid experiment id")
	}
	if err := os.MkdirAll(h.Dir, 0700); err != nil {
		return err
	}
	data, err := json.MarshalIndent(exp, "", "  ")
	if err != nil {
		return err
	}
	tmp, err := os.CreateTemp(h.Dir, ".experiment-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), filepath.Join(h.Dir, exp.ID+".json"))
}

// Get reads a saved experiment by ID.
func (h History) Get(id string) (Experiment, error) {
	if len(id) != 32 {
		return Experiment{}, ErrExperimentNotFound
	}
	for _, r := range id {
		if !((r >= '0' && r <= '9') || (r >= 'a' && r <= 'f')) {
			return Experiment{}, ErrExperimentNotFound
		}
	}
	data, err := os.ReadFile(filepath.Join(h.Dir, id+".json"))
	if errors.Is(err, os.ErrNotExist) {
		return Experiment{}, ErrExperimentNotFound
	}
	if err != nil {
		return Experiment{}, err
	}
	var exp Experiment
	if err := json.Unmarshal(data, &exp); err != nil {
		return Experiment{}, err
	}
	normalizeExperiment(&exp)
	return exp, nil
}

// List returns saved experiments newest first.
func (h History) List() ([]Experiment, error) {
	entries, err := os.ReadDir(h.Dir)
	if errors.Is(err, os.ErrNotExist) {
		return []Experiment{}, nil
	}
	if err != nil {
		return nil, err
	}
	var out []Experiment
	for _, entry := range entries {
		if entry.IsDir() || filepath.Ext(entry.Name()) != ".json" {
			continue
		}
		exp, err := h.Get(entry.Name()[:len(entry.Name())-5])
		if err != nil {
			return nil, err
		}
		out = append(out, exp)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].CreatedAt.After(out[j].CreatedAt) })
	return out, nil
}
